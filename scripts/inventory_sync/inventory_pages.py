"""Publish the Nudge bot's daily inventory snapshots as one wiki page per campaign.

Added 2026-10-17. The bot saves each campaign's snapshot to ``data/inventories/<code>/<YYYY-MM-DD>.json`` in its
public repo; the workflow that publishes the PBP transcripts and encounters pulls those and runs this.

⭐ **The bot's snapshots are the source of truth.** Everything under ``topics/Inventories/`` and the whole of
``inventories.tree`` is generated and overwritten, like the encounter pages. Its own Writerside instance, so the
hand-written table of contents stays as it is.

Idempotent: a run that changes nothing writes nothing.
"""

import argparse
import importlib.util
import json
import sys
from collections import defaultdict
from pathlib import Path
from xml.sax.saxutils import quoteattr

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory_render import page_name, render_page  # noqa: E402


def _load_guard():
    """pbp_sync's whole-wiki duplicate guard, loaded by path (see encounter_pages.py for why not by import)."""
    path = Path(__file__).resolve().parent.parent / "pbp_sync" / "guards.py"
    spec = importlib.util.spec_from_file_location("pbp_sync_guards", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.assert_no_duplicate_topics


assert_no_duplicate_topics = _load_guard()

START_PAGE = "Inventories.md"
WIKI_ROOT = Path(__file__).resolve().parent.parent.parent
TOPICS_DIR = WIKI_ROOT / "Writerside" / "topics"
OUT_DIR = TOPICS_DIR / "Inventories"
TREE_PATH = WIKI_ROOT / "Writerside" / "inventories.tree"


def load_snapshots(source: Path) -> dict[str, list[dict]]:
    """code -> that campaign's readable snapshots, oldest first. A missing folder means none yet, not an error."""
    by_code = defaultdict(list)
    for path in sorted(source.rglob("*.json")) if source.exists() else []:
        try:
            snapshot = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            print(f"Skipping unreadable snapshot {path.name}: {e}")
            continue
        if isinstance(snapshot, dict) and snapshot.get("code") and snapshot.get("date"):
            by_code[snapshot["code"]].append(snapshot)
    return {code: sorted(items, key=lambda s: s["date"]) for code, items in by_code.items()}


def render_index(campaigns: dict[str, list[dict]]) -> str:
    out = ["# Inventories", "",
           "What every character and party carries, recorded each morning, with every change by day. Generated "
           "from the Path Wars Nudge bot's records.", ""]
    if not campaigns:
        out.append("No inventories recorded yet.")
    for code, snapshots in sorted(campaigns.items()):
        latest = snapshots[-1]
        out.append(f"- [{code} {latest.get('campaign') or ''}".rstrip() + f"]({page_name(code)}): "
                   f"{len(snapshots)} day(s) recorded, latest {latest['date']}")
    return "\n".join(out).rstrip("\n") + "\n"


def render_tree(codes: list[str]) -> str:
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!DOCTYPE instance-profile',
           '        SYSTEM "https://resources.jetbrains.com/writerside/1.0/product-profile.dtd">', "",
           "<!-- GENERATED by scripts/inventory_sync - do not edit by hand. -->", "",
           f'<instance-profile id="inventories" name="Inventories" start-page="{START_PAGE}">',
           f'    <toc-element topic="{START_PAGE}">']
    out += [f"        <toc-element topic={quoteattr(page_name(code))}/>" for code in sorted(codes)]
    out += ["    </toc-element>", "</instance-profile>"]
    return "\n".join(out) + "\n"


def _write(path: Path, body: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == body:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return True


def sync(source: Path, out_dir: Path = OUT_DIR, tree_path: Path = TREE_PATH, topics_dir: Path = TOPICS_DIR) -> int:
    """Write every campaign page, the index and the tree; remove pages no snapshot backs. Returns files changed."""
    campaigns = load_snapshots(source)
    changed = sum(_write(out_dir / page_name(code), render_page(snaps)) for code, snaps in campaigns.items())
    changed += _write(out_dir / START_PAGE, render_index(campaigns))
    expected = {page_name(code) for code in campaigns} | {START_PAGE}
    for stale in out_dir.glob("*.md") if out_dir.exists() else []:
        if stale.name not in expected:
            stale.unlink()
            changed += 1
    changed += _write(tree_path, render_tree(list(campaigns)))
    assert_no_duplicate_topics(topics_dir)
    return changed


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, required=True, help="the bot repo's data/inventories")
    args = parser.parse_args(argv)
    print(f"Inventory pages: {sync(args.source)} file(s) changed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
